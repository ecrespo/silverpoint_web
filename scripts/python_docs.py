"""Write the files /docs/python takes from the installed ``silverpoint`` package (PyPI).

    uv run python scripts/python_docs.py           # write assets/python/demo.html and python_builders.json
    uv run python scripts/python_docs.py --check   # fail when either is not what the package writes

The demo is ``python_examples.DEMO`` run as is: its three ``to_html(full_document=False)`` fragments
in a plain page that loads the standalone file this site already serves (``/embed/``), so the page
holds exactly the markup Python writes.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from silverpoint_web import embed_examples as embed  # noqa: E402
from silverpoint_web import python_examples as ex  # noqa: E402

PAGE = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>silverpoint for Python demo</title>
    <!-- Generated by scripts/python_docs.py from python_examples.DEMO (silverpoint {version}). -->
    <script src="/embed/{script}"></script>
    <style>
      html {{ background: #f4efe4; }}
      body {{ margin: 0; padding: 16px; }}
      .grid {{ display: grid; gap: 16px; grid-template-columns: repeat(auto-fit, minmax(260px, 1fr)); }}
      .grid > div {{ min-width: 0; }}
    </style>
  </head>
  <body>
    <div class="grid">
{fragments}
    </div>
  </body>
</html>
"""


def demo_html() -> str:
    import silverpoint

    scope: dict[str, Any] = {}
    exec(ex.DEMO, scope)  # noqa: S102 - the site's own example, run to write its output
    fragments = "\n".join(f"      {fragment}" for fragment in scope["fragments"])
    return PAGE.format(version=silverpoint.__version__, script=embed.STANDALONE_FILE, fragments=fragments)


def builders() -> list[dict[str, Any]]:
    import silverpoint

    entries = []
    for chart in silverpoint.catalog["charts"]:
        name = chart["slug"].replace("-", "_")
        if name not in silverpoint.__all__:
            continue
        entries.append(
            {
                "name": name,
                "chart": chart["slug"],
                "title": chart["title"],
                "family": chart["family"],
                "roles": [{"id": role["id"], "required": role["required"]} for role in chart["roles"]],
            }
        )
    return sorted(entries, key=lambda entry: entry["name"])


def builders_json() -> str:
    return json.dumps(builders(), indent=1) + "\n"


def main() -> int:
    outputs = {ex.ASSETS / "demo.html": demo_html(), ex.BUILDERS_FILE: builders_json()}
    if "--check" in sys.argv:
        stale = [str(path) for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        if stale:
            print("stale (run scripts/python_docs.py):", *stale, sep="\n  ")
            return 1
        print("python docs files are current")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
